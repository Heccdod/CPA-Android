#!/usr/bin/env python3
"""Bundle every source file in the repo into one text file for outside review.

The bundle is meant to be handed to a reviewer that cannot clone the repository, so it has to be
self-contained and honest about what is missing. Three rules shape it:

1. Skip only what cannot be reviewed as text: the git database, the upstream clone (a copy of
   someone else's repository), build output, and binaries.
2. Never silently drop a file. A file that fails to decode is listed with the reason, because a
   bundle that quietly omits a file is worse than one that admits it.
3. Record what was left out and why, at both ends, so a reader knows the bundle is complete with
   respect to source code rather than complete full stop.

Usage:
    python3 scripts/make-audit-bundle.py [output]
"""
import pathlib
import sys

# Directories that hold no first-party source: VCS data, build output, IDE state, and the
# upstream clone (a separate project reviewed on its own).
SKIP_DIRS = {".git", "upstream-cliproxy", "build", ".gradle", ".idea", "libs", "__pycache__",
             ".dsh", "dist", "node_modules"}

# Extensions that are binary or rebuilt from source.
SKIP_EXTS = {".aar", ".apk", ".so", ".jar", ".png", ".webp", ".jpg", ".jpeg", ".gif",
             ".pyc", ".keystore", ".jks", ".zip", ".aab", ".hprof"}

# Files whose content is large and generated, but which a reviewer may still want.
# They are included; this list exists only to document the decision.
LARGE_OK = {"upstream-patches.diff", "assets/models.json"}

root = pathlib.Path(__file__).resolve().parent.parent
out_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "cpa_audit_bundle.txt"

parts = []
included = []
skipped = []
# A skipped directory is reported once by name. The upstream clone alone holds thousands of
# files, and listing each of them buries the part of the report a reader needs: what in *this*
# repository was left out.
skipped_dirs = set()

for p in sorted(root.rglob("*")):
    if not p.is_file():
        continue
    rel = p.relative_to(root)
    # Never bundle the bundle. Without this the output file is picked up on the next run and the
    # file doubles in size every time.
    if p.resolve() == out_path.resolve():
        continue
    skip_dir = next((part for part in rel.parts if part in SKIP_DIRS), None)
    if skip_dir is not None:
        skipped_dirs.add(skip_dir)
        continue
    # An upstream diff is not first-party code: it is the patch we apply to someone else's
    # repository, and a reviewer is better served reading it beside the upstream source. It goes
    # to its own file so it does not dominate the bundle.
    if rel.as_posix() == "upstream-patches.diff":
        skipped.append((rel.as_posix(), "separate file: cpa_upstream_patch.txt"))
        continue
    if p.suffix.lower() in SKIP_EXTS:
        skipped.append((rel.as_posix(), "binary " + p.suffix.lower()))
        continue
    try:
        text = p.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        skipped.append((rel.as_posix(), "not utf-8: %s" % exc))
        parts.append("====== FILE: %s (SKIPPED: not UTF-8) ======\n" % rel.as_posix())
        continue
    except OSError as exc:
        skipped.append((rel.as_posix(), "unreadable: %s" % exc))
        continue
    included.append((rel.as_posix(), len(text)))
    parts.append("====== FILE: %s ======\n%s\n" % (rel.as_posix(), text))

header = [
    "CPA-Android source bundle",
    "",
    "Generated by scripts/make-audit-bundle.py from the working tree.",
    "Every text file in the repository is included verbatim, except the categories below.",
    "",
    "Excluded on purpose:",
    "  .git/                 version-control database",
    "  upstream-cliproxy/    a clone of router-for-me/CLIProxyAPI, reviewed separately",
    "  app/libs/             cliproxy.aar (generated by gomobile bind)",
    "  build output          build/, .gradle/, dist/, __pycache__/",
    "  binaries              *.aar *.apk *.so *.jar *.png *.webp *.pyc *.zip",
    "",
    "Included: %d files, %d characters." % (len(included), sum(n for _, n in included)),
    "",
    "Note: go-bridge/go.mod has a replace directive pointing at ../upstream-cliproxy, which is",
    "not part of this bundle. The bridge cannot be compiled from the bundle alone; that is",
    "expected and is what scripts/apply-upstream-patch.sh sets up.",
    "",
]

body = "\n".join(header) + "\n".join(parts)

footer = [
    "",
    "====== END OF BUNDLE ======",
    "",
    "Directories excluded whole (%d): %s" % (len(skipped_dirs), ", ".join(sorted(skipped_dirs))),
    "",
    "Individual files excluded (%d):" % len(skipped),
]
for name, why in skipped:
    footer.append("  %-60s %s" % (name, why))

out_path.write_text(body + "\n".join(footer) + "\n", encoding="utf-8")

# The upstream patch ships beside the bundle: it is a diff against someone else's repository,
# 539 KB of it, and burying the first-party source under it helps nobody.
patch = root / "upstream-patches.diff"
if patch.exists():
    side = out_path.with_name("cpa_upstream_patch.txt")
    side.write_text(
        "CPA-Android local patches against router-for-me/CLIProxyAPI\n"
        "Applied by scripts/apply-upstream-patch.sh; the source it patches is not in this bundle.\n"
        "\n" + patch.read_text(encoding="utf-8"),
        encoding="utf-8",
    )
    print("wrote %s" % side)
print("wrote %s" % out_path)
print("included %d files (%d chars), skipped %d" % (len(included), sum(n for _, n in included), len(skipped)))
