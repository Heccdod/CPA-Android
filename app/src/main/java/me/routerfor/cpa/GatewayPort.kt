package me.routerfor.cpa

import android.content.Context
import java.io.File

/**
 * The loopback port the gateway is actually listening on.
 *
 * Three call sites used to hardcode 8317 (Credentials, OauthLauncher, Quota, plus the panel URL).
 * The port lives in config.yaml under server.port and the user can change it, so a hardcoded
 * value silently points the client at a socket nobody is listening on: the app looks connected
 * while every request fails.
 *
 * Resolution order, most authoritative first:
 *  1. the address the engine reports while it is running (it is the socket that accepted the
 *     probe, not a promise);
 *  2. server.port in config.yaml, for the window before the engine is up;
 *  3. [FALLBACK_PORT].
 */
object GatewayPort {

    const val FALLBACK_PORT = 8317

    @Volatile
    private var cached: Int = FALLBACK_PORT

    /** Host and port as a URL prefix, e.g. `http://127.0.0.1:8317`. */
    fun base(): String = "http://127.0.0.1:" + port()

    /**
     * The port to build loopback URLs with.
     *
     * Deliberately not "ask the engine": its listen address falls back to the compiled-in default
     * whenever nothing is running, so the answer would overwrite a correct cached port with 8317
     * the moment the gateway is down — and [isRunning] itself opens a 150ms TCP connection, which
     * has no business on the main thread. The cached value is refreshed from config.yaml when the
     * service starts (and on app start), which is exactly when the port can have changed.
     */
    fun port(): Int = cached

    /** Records a port the engine reported, e.g. after a start that used a different one. */
    fun note(address: String) {
        val live = portFromAddress(address)
        if (live > 0) cached = live
    }

    /**
     * Re-reads the configured port. Cheap and safe to call from a background thread on every
     * service start; the file is a few kilobytes.
     */
    fun refresh(context: Context) {
        cached = portFromConfig(File(context.filesDir, "config.yaml")) ?: cached
    }

    /** Pulls the port out of `host:port`, tolerating a bare address or an empty string. */
    fun portFromAddress(address: String): Int {
        val at = address.lastIndexOf(':')
        if (at < 0 || at == address.length - 1) return -1
        val digits = address.substring(at + 1).trim()
        if (digits.isEmpty() || !digits.all { it in '0'..'9' }) return -1
        val port = digits.toIntOrNull() ?: return -1
        return if (port in 1..65535) port else -1
    }

    /**
     * Reads server.port without a YAML parser.
     *
     * Deliberately not a general parser: config.yaml is generated by this app, and the only thing
     * needed here is the scalar under the top-level `server:` block. Anything that does not look
     * like that shape returns null and the caller keeps its previous value — a wrong answer here
     * would be worse than a stale one.
     */
    fun portFromConfig(file: File): Int? {
        if (!file.isFile) return null
        val text = runCatching { file.readText() }.getOrNull() ?: return null
        var inServer = false
        var indentOfServer = 0
        for (raw in text.lineSequence()) {
            val line = raw.substringBefore(" #").trimEnd()
            if (line.isBlank() || line.trimStart().startsWith("#")) continue
            val indent = line.length - line.trimStart().length
            val body = line.trim()
            if (!inServer) {
                if (body == "server:") {
                    inServer = true
                    indentOfServer = indent
                }
                continue
            }
            // A line at or left of the server key's own indent closes the block.
            if (indent <= indentOfServer) {
                inServer = false
                if (body == "server:") {
                    inServer = true
                    indentOfServer = indent
                }
                continue
            }
            if (body.startsWith("port:")) {
                val value = body.removePrefix("port:").trim().trim('"', '\'')
                val port = value.toIntOrNull() ?: return null
                return if (port in 1..65535) port else null
            }
        }
        return null
    }
}
